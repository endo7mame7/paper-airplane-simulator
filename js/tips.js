// 前と同じにならないように、ランダムに並べた順番を返す
export function shuffledTips(random = Math.random) {
  const a = TIPS.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
